type NoteTableProps = {
  headers: string[];
  rows: string[][];
};

export function NoteTable({ headers, rows }: NoteTableProps) {
  return (
    <div className="note-table-wrap">
      <table className="note-table">
        <thead>
          <tr>
            {headers.map((header) => (
              <th key={header} scope="col">
                {header}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((row) => (
            <tr key={row.join('|')}>
              {row.map((cell, index) => (
                <td key={`${cell}-${index}`}>{cell}</td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
